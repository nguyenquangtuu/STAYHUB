package com.stayhub.app.data.model.request;

import com.google.gson.annotations.SerializedName;

/**
 * Request hoàn tất thông tin người dùng mới sau khi xác thực OTP
 */
public class CompleteRegistrationRequest {

    @SerializedName("full_name")
    private String fullName;

    @SerializedName("email")
    private String email;

    @SerializedName("phone")
    private String phone;

    public CompleteRegistrationRequest() {
    }

    public CompleteRegistrationRequest(String fullName, String email, String phone) {
        this.fullName = fullName;
        this.email = email;
        this.phone = phone;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }
}
